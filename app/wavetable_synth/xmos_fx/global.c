float delayLine(float xIn, float* delayBuf, int delayLen, int* wrPtr)
{
	int rdPointer = 0;
	float delayOut = 0.f;

	rdPointer = *wrPtr - delayLen;
	if(rdPointer < 0) {
		rdPointer += delayLen;
	}

	delayOut = delayBuf[rdPointer];

	delayBuf[*wrPtr] = xIn;

	(*wrPtr)++;
	if(*wrPtr >= delayLen){
		*wrPtr = 0;
	}

	return delayOut;
}


float delayLineVar(float xIn, float* delayBuf, float knobSize, int minLen, int maxLen, int* wrPtr)
{
	int d = 0;
	int rdPointer = 0;
	float rate = 0;
	float frac = 0.f;
	float f1 = 0.f, f2 = 0.f;
	float delayOut = 0.f;
	float delayLen;

	delayLen = minLen + knobSize * (maxLen - minLen);


	d = (int)delayLen;
	frac = delayLen - d;

	rdPointer = *wrPtr - d;
	if(rdPointer < 0) {
		rdPointer += maxLen;
	}
	f1 = delayBuf[rdPointer];

	rdPointer -= 1;
	if(rdPointer < 0) {
		rdPointer += maxLen;
	}
	f2 = delayBuf[rdPointer];

	delayOut = f2 * frac + f1 * (1.f - frac);

	delayBuf[*wrPtr] = xIn;

	(*wrPtr)++;
	if(*wrPtr >= maxLen){
		*wrPtr = 0;
	}

	return delayOut;
}




